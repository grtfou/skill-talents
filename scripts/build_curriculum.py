    lookup = {skill["id"]: skill for skill in skills}
    lane_previous, previous = {}, {}
    for skill in skills:
        lane_key = (skill["branch"], skill["lane"])
        lane_previous[skill["id"]] = previous.get(lane_key)
        previous[lane_key] = skill["id"]
    layout_levels, layout_visiting = {}, set()

    def layout_level(identifier):
        if identifier in layout_levels:
            return layout_levels[identifier]
        if identifier in layout_visiting:
            raise ValueError(f"地圖排版相依循環：{identifier}")
        layout_visiting.add(identifier)
        skill = lookup[identifier]
        parents = [p for p in skill["prerequisites"] if lookup[p]["branch"] == skill["branch"]]
        if lane_previous[identifier]:
            parents.append(lane_previous[identifier])
        level = max((layout_level(p) + 1 for p in parents), default=0)
        layout_levels[identifier] = level
        layout_visiting.remove(identifier)
        return level

